#!/usr/bin/env python3
"""Convert the supplied SVG to the panel's small, tintable alpha mask.

Host-only tool: requires Pillow and Playwright/Chromium. The generated header is
tracked, so firmware builds and the device need no SVG/browser dependencies.
"""
import argparse
import base64
import hashlib
from pathlib import Path
from PIL import Image
from playwright.sync_api import sync_playwright

TOP = Path(__file__).resolve().parents[1]
SVG = TOP / 'devices/u30pro/assets/high-rail.svg'
HEADER = TOP / 'devices/u30pro/native/tools/ui/high_rail_icon.h'
SIZE = 18


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--browser')
    args = parser.parse_args()
    source = SVG.read_bytes()
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, **({'executable_path': args.browser} if args.browser else {}))
        page = browser.new_page()
        alpha = page.evaluate('''async ([url,size])=>{
            const img=new Image();img.src=url;await img.decode();
            const c=document.createElement('canvas');c.width=c.height=size;
            const ctx=c.getContext('2d');ctx.drawImage(img,0,0,size,size);
            const pixels=ctx.getImageData(0,0,size,size).data;
            return Array.from({length:size*size},(_,i)=>pixels[i*4+3]);
        }''', ['data:image/svg+xml;base64,' + base64.b64encode(source).decode(), SIZE * 8])
        browser.close()
    mask = Image.frombytes('L', (SIZE * 8, SIZE * 8), bytes(alpha)).resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    values = mask.tobytes()
    rows = ['\t' + ', '.join(f'0x{x:02x}' for x in values[i:i+SIZE]) + ',' for i in range(0, len(values), SIZE)]
    HEADER.write_text('/* User-supplied SVG; generated by tools/generate-high-rail-icon.py.\n'
        f' * Source SHA-256: {hashlib.sha256(source).hexdigest()} */\n'
        '#ifndef U30PRO_HIGH_RAIL_ICON_H\n#define U30PRO_HIGH_RAIL_ICON_H\n'
        f'#define HIGH_RAIL_ICON_SIZE {SIZE}\n'
        'static const unsigned char high_rail_icon_alpha[HIGH_RAIL_ICON_SIZE * HIGH_RAIL_ICON_SIZE] = {\n' +
        '\n'.join(rows) + '\n};\n#endif\n', encoding='utf-8', newline='\n')
    print(f'Generated {SIZE}x{SIZE} alpha mask ({len(values)} bytes): {HEADER}')


if __name__ == '__main__':
    main()
